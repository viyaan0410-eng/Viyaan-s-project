def draw_line(x0, y0, x1, y1):
    t.penup()
    t.goto(x0,y0)
    t.pendown()
    t.goto(x1,y1)


def draw_rectangle(x0,y0, len, htg, clr):
    t.fillcolor(clr)
    t.begin_fill()
    draw_line(x0, y0, x0+len , y0)
    draw_line(x0+len, y0, x0+len , y0+htg)
    draw_line(x0+len, y0+htg, x0, y0+htg)
    draw_line(x0, y0+htg, x0 , y0)
    t.end_fill()

